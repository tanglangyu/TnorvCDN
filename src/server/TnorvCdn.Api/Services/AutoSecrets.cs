using System.Security.Cryptography;
using System.Text.Json;

namespace TnorvCdn.Api.Services;

/// <summary>
/// 首次启动随机密钥保障：Jwt:Key 缺失 / 为占位符时，自动生成强随机密钥并
/// 持久化到应用目录下的 appsettings.Generated.json（0600 权限），重启后保持不变。
/// 之后运行时与安装引导都以此为准；多实例部署需显式配置相同密钥。
/// 生成的文件损坏或不可写时自动降级：删除重建 / 仅内存生效，绝不阻断启动。
/// </summary>
public static class AutoSecrets
{
    private static bool _autoGenerated;

    /// <summary>当前生效的 Jwt:Key 是否为启动时自动生成（供安装引导展示）。</summary>
    public static bool JwtKeyAutoGenerated => _autoGenerated;

    /// <summary>在 builder.Build() 之前调用：注册 Generated 配置源并按需生成密钥。</summary>
    public static void EnsureJwtKey(WebApplicationBuilder builder)
    {
        var path = Path.Combine(builder.Environment.ContentRootPath, "appsettings.Generated.json");
        TryAddGeneratedSource(builder.Configuration, path);

        var key = builder.Configuration["Jwt:Key"];
        if (!string.IsNullOrWhiteSpace(key) && !key.Contains("CHANGE-ME", StringComparison.OrdinalIgnoreCase))
            return; // 已显式配置（文件/环境变量），尊重运维配置

        key = Convert.ToBase64String(RandomNumberGenerator.GetBytes(48));
        try
        {
            var json = JsonSerializer.Serialize(new { Jwt = new { Key = key } }, new JsonSerializerOptions { WriteIndented = true });
            File.WriteAllText(path, json);
            try { File.SetUnixFileMode(path, UnixFileMode.UserRead | UnixFileMode.UserWrite); } catch { /* 非 Unix 平台忽略 */ }
        }
        catch (Exception ex)
        {
            // 文件不可写（只读卷等）：密钥仅本次运行有效，不阻断启动
            Console.WriteLine($"[AutoSecrets] appsettings.Generated.json 写入失败（密钥仅本次运行有效）: {ex.Message}");
        }
        builder.Configuration["Jwt:Key"] = key;
        _autoGenerated = true;
    }

    private static void TryAddGeneratedSource(ConfigurationManager configuration, string path)
    {
        try
        {
            // 预校验 JSON：损坏文件在 AddJsonFile 前删除（配置读取是延迟构建，坏文件会让首次读key时才抛异常）
            if (File.Exists(path))
            {
                using var _ = JsonDocument.Parse(File.ReadAllText(path));
            }
            configuration.AddJsonFile(path, optional: true, reloadOnChange: false);
        }
        catch
        {
            // 生成的文件损坏（手工误编辑等）：删除后重载，仍不可用则跳过（走生成逻辑）
            try
            {
                File.Delete(path);
                configuration.AddJsonFile(path, optional: true, reloadOnChange: false);
            }
            catch { /* 彻底不可用：忽略，后续按未配置处理 */ }
        }
    }

    /// <summary>随机十六进制串（小写），用于模板密钥/令牌等场景。</summary>
    public static string RandomHex(int bytes) => Convert.ToHexString(RandomNumberGenerator.GetBytes(bytes)).ToLowerInvariant();
}
